def json_hash(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                     separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def atomic_json(path: Path, value: Any) -> None:
    """Atomic create-only; existing data are never silently replaced."""
    import os
    import uuid
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise FileExistsError(f'Output exists: {path}')
    temp = path.with_name('.' + path.name + '.incomplete-' + uuid.uuid4().hex)
    try:
        with temp.open('x', encoding='utf-8') as f:
            json.dump(value, f, ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False)
            f.write('\n')
            f.flush()
            os.fsync(f.fileno())
        if path.exists():
            raise FileExistsError(path)
        temp.rename(path)
    finally:
        temp.unlink(missing_ok=True)


def atomic_jsonl(path: Path, records: list[dict]) -> None:
    import os
    import uuid
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise FileExistsError(path)
    temp = path.with_name('.' + path.name + '.incomplete-' + uuid.uuid4().hex)
    try:
        with temp.open('x', encoding='utf-8') as f:
            for record in records:
                f.write(json.dumps(record, sort_keys=True, ensure_ascii=False,
                                   allow_nan=False) + '\n')
            f.flush()
            os.fsync(f.fileno())
        if path.exists():
            raise FileExistsError(path)
        temp.rename(path)
    finally:
        temp.unlink(missing_ok=True)


def finite_scalar(x: torch.Tensor) -> float:
    y = float(x.detach().cpu().item())
    if not math.isfinite(y):
        raise ValueError('Nonfinite diagnostic')
    return y


def local_delta(state: dict[str, torch.Tensor], condition: str,
                layer: int, base_fp32: torch.Tensor) -> torch.Tensor:
    """Effective FP32 delta for one down_proj. No dense adapter merges/rounding.

    Full/L2SP starting point is the original FP32 model; adapter corrections
    use the exact alpha/r scale and OPLoRA's saved frozen U/V projections.
    """
    prefix = f'model.layers.{layer}.mlp.down_proj'
    if condition in ('full_mid', 'full_final', 'l2sp_final'):
        return state[prefix + '.weight'].to(base_fp32.device, torch.float32) - base_fp32
    if condition not in ('lora4_final', 'lora16_final', 'oplora16_final'):
        raise ValueError(condition)
    a = state[prefix + '.lora_A'].to(base_fp32.device, torch.float32)
    b = state[prefix + '.lora_B'].to(base_fp32.device, torch.float32)
    if condition == 'oplora16_final':
        u = state[prefix + '.basis_u'].to(base_fp32.device, torch.float32)
        v = state[prefix + '.basis_v'].to(base_fp32.device, torch.float32)
        ready = state[prefix + '.basis_ready']
        if not bool(ready.item()):
            raise ValueError(f'OPLoRA basis not ready at layer {layer}')
        a = a - (a @ v) @ v.T
        b = b - u @ (u.T @ b)
    rank, alpha = ((4, 8) if condition == 'lora4_final' else (16, 32))
    if a.shape[0] != rank or b.shape[1] != rank:
        raise ValueError(f'Unexpected adapter rank: {condition} {layer}')
    return (b @ a) * (alpha / rank)


def weight_stats(delta: torch.Tensor, w0: torch.Tensor,
                 u: torch.Tensor) -> dict[str, float | None]:
    """rho_k and eta from assignment; U is shared starting-weight basis."""
    delta = delta.float()
    w0 = w0.float()
    u = u.float()
    if delta.shape != w0.shape or u.shape[0] != w0.shape[0]:
        raise ValueError('Weight/basis dimensions disagree')
    norm_sq = (delta.double() ** 2).sum()
    denom_sq = (w0.double() ** 2).sum()
    if not bool(denom_sq > 0):
        raise ValueError('Zero starting-weight norm')
    proj = u @ (u.T @ delta)
    proj_sq = (proj.double() ** 2).sum()
    rho = None if not bool(norm_sq > 0) else finite_scalar(proj_sq / norm_sq)
    eta = finite_scalar(torch.sqrt(norm_sq / denom_sq))
    if rho is not None and not (-1e-5 <= rho <= 1.0005):
        raise ValueError(f'Invalid rho: {rho}')
    return {'rho_k': rho, 'eta': eta, 'delta_fro': finite_scalar(torch.sqrt(norm_sq)),
            'w0_fro': finite_scalar(torch.sqrt(denom_sq))}


def activation_ratio(delta: torch.Tensor, w0: torch.Tensor,
                     z: torch.Tensor) -> float:
    z = z.to(device=delta.device, dtype=torch.float32)
    numerator = torch.linalg.vector_norm(delta.float() @ z)
    denominator = torch.linalg.vector_norm(w0.float() @ z) + 1e-8
    return finite_scalar(numerator / denominator)


def unique_displacement(base_model, state: dict[str, torch.Tensor], device: str) -> dict:
    """Full-model ||theta-theta0||2 over unique named parameters (tied once)."""
    total = 0.0
    count = 0
    names = []
    with torch.no_grad():
        for name, original in base_model.named_parameters(remove_duplicate=True):
            if name not in state:
                raise ValueError(f'Missing full-FT parameter {name}')
            trained = state[name]
            if trained.shape != original.shape:
                raise ValueError(f'Parameter shape mismatch {name}')
            a = trained.to(device=device, dtype=torch.float32)
            b = original.detach().to(device=device, dtype=torch.float32)
            diff = a - b
            total += finite_scalar((diff.double() ** 2).sum())
            count += original.numel()
            names.append(name)
            del a, b, diff
    return {'displacement_l2': math.sqrt(total), 'unique_parameters': count,
            'unique_tensor_count': len(names), 'parameter_names_sha256': json_hash(names)}


def _read_baseline_prompt(sample: dict, benchmark: str) -> str:
    """Extract the *actual logged* stock prompt, not a reconstructed guess."""
    args = sample.get('arguments')
    if not isinstance(args, list) or not args:
        raise ValueError(f'No logged request arguments for {benchmark}')
    first = args[0]
    if not isinstance(first, (list, tuple)) or not first or not isinstance(first[0], str):
        raise ValueError(f'Unexpected logged arguments for {benchmark}: {str(first)[:120]}')
    if benchmark == 'hellaswag':
        if len(args) != 4 or any(not isinstance(a, (list, tuple)) or a[0] != first[0]
                                 for a in args):
            raise ValueError('HellaSwag choices do not share one stock context')
    return first[0]


def select_probes(artifacts: Path, output: Path, *, smoke: bool) -> dict:
    """Select by fixed seed independently of predictions; retrospective disclosure."""
    path = output / 'activation' / 'probe_ids.json'
    if path.exists():
        saved = json.loads(path.read_text())
        if saved.get('seed') != SEED or saved.get('source') != 'baseline_logged_requests':
            raise ValueError('Existing probe selection has different provenance')
        return saved
    rng = random.Random(SEED)
    entries = []
    for benchmark in ('gsm8k_cot', 'hellaswag'):
        n = BENCHMARKS[benchmark]['count']
        chosen = rng.sample(range(n), 2 if smoke else 32)
        by_id = {}
        source = artifacts / 'evaluation' / 'baseline' / benchmark / 'samples.jsonl'
        for line in source.open(encoding='utf-8'):
            item = json.loads(line)
            idx = int(item['doc_id'])
            if idx in chosen:
                if idx in by_id:
                    raise ValueError(f'Duplicate baseline doc_id {idx}')
                by_id[idx] = _read_baseline_prompt(item, benchmark)
        if set(by_id) != set(chosen):
            raise ValueError(f'Missing baseline prompt IDs for {benchmark}: {set(chosen)-set(by_id)}')
        for idx in chosen:
            prompt = by_id[idx]
            entries.append({'benchmark': benchmark, 'doc_id': idx, 'prompt': prompt,
                            'prompt_sha256': hashlib.sha256(prompt.encode()).hexdigest()})
    saved = {
        'seed': SEED, 'source': 'baseline_logged_requests',
        'selection_method': 'random.Random(6304), GSM8K sample then HellaSwag sample',
        'selection_timing': 'retrospective_after_benchmark_results_were_inspected',
        'protocol_deviation': 'Manual requests probe selection before inspecting model results; this selection was made later, without using outcomes.',
        'model_id': MODEL_ID, 'model_revision': MODEL_REVISION,
        'entries': entries, 'smoke': smoke,
    }
    atomic_json(path, saved)
    return saved


def _prompt_ids(tokenizer, prompt: str, benchmark: str) -> torch.Tensor:
    """Tokenize the exact request string already formatted by lm-eval.

    GSM8K logged requests already contain the nonthinking chat template.
    HellaSwag logged requests contain stock completion contexts.
    """
    if benchmark not in ('gsm8k_cot', 'hellaswag'):
        raise ValueError(f'Unknown probe benchmark: {benchmark}')
    result = tokenizer(
        prompt, add_special_tokens=False, return_tensors='pt'
    )['input_ids']
    if result.ndim != 2 or result.shape[0] != 1 or result.shape[1] < 1:
        raise ValueError('Empty or invalid prompt tokens')
    return result

def build_probe_cache(artifacts: Path, output: Path, device: str, *, smoke: bool) -> dict:
    """Cache baseline pre-down_proj inputs for all probes; no answer generation."""
    import os
    import uuid
    ids = select_probes(artifacts, output, smoke=smoke)
    dest = output / 'activation' / 'starting_inputs.pt'
    meta = output / 'activation' / 'starting_inputs_meta.json'
    if dest.exists() and meta.exists():
        saved_meta = json.loads(meta.read_text())
        if saved_meta.get('probe_sha256') != json_hash(ids) or saved_meta.get('cache_sha256') != sha256_file(dest):
            raise ValueError('Existing activation cache does not match probe selection')
        return torch.load(dest, map_location='cpu', weights_only=True)
    if dest.exists() or meta.exists():
        raise ValueError('Partial probe cache; investigate before rerunning')
    # Official GSM8K generation audit records actual harness prompt-token hashes.
    # Use it to detect accidental chat-template/prompt mismatches.
    audit_path = (artifacts / 'evaluation' / 'baseline' / 'gsm8k_cot' /
                  'generation_token_audit.jsonl')
    official_gsm_token_hashes = {
        json.loads(line)['prompt_token_hash'] for line in audit_path.open(encoding='utf-8')
        if line.strip()
    }
    if len(official_gsm_token_hashes) != BENCHMARKS['gsm8k_cot']['count']:
        raise ValueError('Unexpected baseline GSM8K prompt-token audit count')
    model, tokenizer, manifest = load_model_for_evaluation('baseline', device=device)
    cache = {}
    hooks = []
    captured = {}
    try:
        for layer in LAYERS:
            module = model.model.layers[layer].mlp.down_proj
            def hook(_module, inputs, layer=layer):
                x = inputs[0]
                if x.ndim != 3 or x.shape[0] != 1:
                    raise ValueError('Expected one unpadded prompt at a time')
                captured[layer] = x[0, -1].detach().float().cpu().clone()
            hooks.append(module.register_forward_pre_hook(hook))
        for i, entry in enumerate(ids['entries']):
            captured.clear()
            tokens = _prompt_ids(tokenizer, entry['prompt'], entry['benchmark']).to(device)
            with torch.inference_mode():
                model(input_ids=tokens, use_cache=False)
            if set(captured) != set(LAYERS):
                raise ValueError(f'Missing activation hook(s) for probe {i}')
            for layer in LAYERS:
                cache[f'{i}:{layer}'] = captured[layer]
            entry['token_count'] = int(tokens.shape[1])
            entry['token_ids_sha256'] = json_hash(tokens[0].cpu().tolist())
            if (entry['benchmark'] == 'gsm8k_cot' and
                    entry['token_ids_sha256'] not in official_gsm_token_hashes):
                raise ValueError(f'GSM8K prompt tokenization differs from official harness: doc_id={entry["doc_id"]}')
            if (i + 1) % 8 == 0:
                print(f'  Captured {i+1}/{len(ids["entries"])} probes', flush=True)
        # Save enriched prompt selection only in cache metadata (original IDs immutable).
        dest.parent.mkdir(parents=True, exist_ok=True)
        temp = dest.with_name('.' + dest.name + '.incomplete-' + uuid.uuid4().hex)
        try:
            torch.save(cache, temp)
            if dest.exists():
                raise FileExistsError(dest)
            temp.rename(dest)
        finally:
            temp.unlink(missing_ok=True)
        atomic_json(meta, {'probe_sha256': json_hash(select_probes(artifacts, output, smoke=smoke)),
                           'cache_sha256': sha256_file(dest), 'layers': list(LAYERS),
                           'entries_with_token_metadata': ids['entries'],
                           'baseline_manifest': manifest,
                           'tokenization': 'gsm8k: nonthinking chat; hellaswag: stock completion'})
    finally:
        for h in hooks:
            h.remove()
        del model
        if device.startswith('cuda'):
            torch.cuda.empty_cache()
    return cache


def collect_diagnostics(artifacts: Path, output: Path, device: str, *, smoke: bool,
                        conditions: tuple[str, ...]) -> None:
    from transformers import AutoModelForCausalLM
    # Cache uses FP16 original baseline, exactly as in official benchmark inference.
    cache = build_probe_cache(artifacts, output, device, smoke=smoke)
    ids = select_probes(artifacts, output, smoke=smoke)
    print('Loading pinned FP32 starting model for weight diagnostics ...', flush=True)
    original = AutoModelForCausalLM.from_pretrained(
        MODEL_ID, revision=MODEL_REVISION, dtype=torch.float32,
        attn_implementation='eager').cpu().eval()
    w0 = {layer: original.model.layers[layer].mlp.down_proj.weight.detach().to(device).float()
          for layer in LAYERS}
    # OPLoRA's saved U defines the actual protected output subspace.
    op_checkpoint = checkpoint_directory(artifacts, 'oplora16_final')
    op_state, _, op_meta = verified_state(op_checkpoint, 'oplora16_final')
    bases = {layer: op_state[f'model.layers.{layer}.mlp.down_proj.basis_u'].to(device).float()
             for layer in LAYERS}
    for layer, u in bases.items():
        gram = u.T @ u
        error = float((gram - torch.eye(gram.shape[0], device=device)).abs().max().item())
        if error > 2e-3:
            raise ValueError(f'OPLoRA basis not orthonormal at layer {layer}: {error}')
    del op_state
    for condition in conditions:
        if condition not in TRAINED:
            raise ValueError(f'Diagnostics require trained condition: {condition}')
        weight_path = output / 'weight' / f'{condition}.json'
        activation_path = output / 'activation' / f'{condition}.jsonl'
        if weight_path.exists() and activation_path.exists():
            existing = json.loads(weight_path.read_text())
            n = sum(1 for line in activation_path.open() if line.strip())
            if (existing.get('condition') != condition or
                existing.get('probe_selection_sha256') != json_hash(ids) or
                len(existing.get('weights', [])) != 3 or n != 3 * len(ids['entries'])):
                raise ValueError(f'Existing diagnostics invalid or incomplete: {condition}')
            print(f'SKIP existing diagnostics: {condition} (counts and probe hash verified)', flush=True)
            continue
        if weight_path.exists() or activation_path.exists():
            raise ValueError(f'Partial diagnostic outputs for {condition}; investigate first')
        ckpt = checkpoint_directory(artifacts, condition)
        print(f'Loading trusted checkpoint: {condition}', flush=True)
        state, spec, meta = verified_state(ckpt, condition)
        rows = []
        acts = []
        for layer in LAYERS:
            delta = local_delta(state, condition, layer, w0[layer])
            stats = weight_stats(delta, w0[layer], bases[layer])
            if condition == 'oplora16_final' and stats['rho_k'] is not None and stats['rho_k'] > 2e-3:
                raise ValueError(f'Unexpectedly large OPLoRA protected-subspace overlap: {stats}')
            rows.append({'condition': condition, 'layer': layer, 'protection_rank': PROTECTION_RANK,
                         **stats})
            for i, entry in enumerate(ids['entries']):
                acts.append({'condition': condition, 'layer': layer,
                             'benchmark': entry['benchmark'], 'doc_id': entry['doc_id'],
                             'prompt_sha256': entry['prompt_sha256'],
                             'r_z': activation_ratio(delta, w0[layer], cache[f'{i}:{layer}'])})
            del delta
        displacement = (unique_displacement(original, state, device)
                        if condition in ('full_mid', 'full_final', 'l2sp_final') else None)
        # State hash was verified by verified_state().
        record = {'condition': condition, 'model_id': MODEL_ID,
                  'model_revision': MODEL_REVISION, 'checkpoint_sha256': meta['state_sha256'],
                  'checkpoint_update': meta['completed_updates'], 'starting_basis_source':
                  'oplora16_final checkpoint frozen basis_u',
                  'basis_checkpoint_sha256': op_meta['state_sha256'],
                  'starting_weight': 'pinned original FP32 Qwen3 weights',
                  'activation_inputs': 'pinned original FP16 Qwen3 baseline',
                  'weights': rows, 'displacement': displacement,
                  'probe_selection_sha256': json_hash(ids),
                  'probe_cache_sha256': sha256_file(output / 'activation' / 'starting_inputs.pt'),
                  'diagnostic_dtype': 'float32 (norm squares accumulated in float64)'}
        if len(rows) != 3 or len(acts) != len(ids['entries']) * 3:
            raise AssertionError('Unexpected diagnostic record counts')
        atomic_json(weight_path, record)
        atomic_jsonl(activation_path, acts)
        print(f'  Saved {len(rows)} weight rows, {len(acts)} activation rows', flush=True)
        del state
        if device.startswith('cuda'):
            torch.cuda.empty_cache()


def read_qualitative_yaml(path: Path) -> list[dict]:
    import yaml
    data = yaml.safe_load(Path(path).read_text(encoding='utf-8'))
    if not isinstance(data, list) or len(data) != 24:
        raise ValueError('Expected 24 original qualitative questions')
    ids = [d['id'] for d in data]
    if len(set(ids)) != 24 or any(len(d.get('paraphrases', [])) != 1 for d in data):
        raise ValueError('Invalid qualitative prompt inventory')
    plain = [x for x in ids if not x.endswith(('_json', '_template'))]
    j = [x for x in ids if x.endswith('_json')]
    t = [x for x in ids if x.endswith('_template')]
    if len(plain) != len(j) or len(j) != len(t) or len(plain) != 8:
        raise ValueError('Expected eight prompts in each format')
    if plain[0] != FIRST_LAST[0] or plain[-1] != FIRST_LAST[1]:
        raise ValueError('Underlying question order differs from expected original')
    return data


def _qual_messages(item: dict) -> list[dict]:
    messages = []
    if item.get('system'):
        messages.append({'role': 'system', 'content': item['system']})
    messages.append({'role': 'user', 'content': item['paraphrases'][0]})
    return messages



def _qual_input_ids(tokenizer, messages: list[dict], device: str) -> torch.Tensor:
    """Support tensor and BatchEncoding outputs across Transformers versions."""
    encoded = tokenizer.apply_chat_template(
        messages, tokenize=True, add_generation_prompt=True,
        enable_thinking=False, return_tensors='pt')
    ids = encoded['input_ids'] if hasattr(encoded, 'keys') else encoded
    if (not isinstance(ids, torch.Tensor) or ids.ndim != 2 or
        ids.shape[0] != 1 or ids.shape[1] < 1):
        raise ValueError('Invalid qualitative tokenization')
    return ids.to(device)


def collect_qualitative(artifacts: Path, output: Path, device: str, yaml_path: Path,
                        *, smoke: bool, conditions: tuple[str, ...]) -> None:
    prompts = read_qualitative_yaml(yaml_path)
    if smoke:
        prompts = [prompts[0], prompts[8], prompts[16]]
    yaml_sha = sha256_file(yaml_path)
    if yaml_sha != QUALITATIVE_YAML_SHA256:
        raise ValueError(f'Qualitative YAML hash changed: {yaml_sha}; expected {QUALITATIVE_YAML_SHA256}')
    for condition in conditions:
        if condition not in ALL:
            raise ValueError(condition)
        checkpoint = checkpoint_directory(artifacts, condition)
        dest = output / 'qualitative' / condition
        if all((dest / (p['id'] + '.json')).exists() for p in prompts):
            for p in prompts:
                existing = json.loads((dest / (p['id'] + '.json')).read_text())
                if (existing.get('condition') != condition or
                    existing.get('question_id') != p['id'] or
                    existing.get('yaml_sha256') != sha256_file(yaml_path)):
                    raise ValueError(f'Existing qualitative output differs: {condition}/{p["id"]}')
            print(f'SKIP {condition}: all {len(prompts)} qualitative outputs verified', flush=True)
            continue
        print(f'Loading qualitative model {condition}', flush=True)
        is_adapter = condition in ('lora4_final', 'lora16_final', 'oplora16_final')
        load_started = time.perf_counter()
        model, tokenizer, manifest = load_model_for_evaluation(
            condition, device=device, checkpoint=checkpoint,
            merge_adapters=not is_adapter)
        if device.startswith('cuda'):
            torch.cuda.synchronize(device)
        load_seconds = time.perf_counter() - load_started
        if is_adapter:
            def sync():
                if device.startswith('cuda'):
                    torch.cuda.synchronize(device)
            # Explicitly measure effective-factor export overhead (including
            # OPLoRA projection) and adapter merging, separately from loading.
            start = time.perf_counter()
            exported = 0
            with torch.no_grad():
                for layer in model.model.layers:
                    for group_name, name in (
                        ('self_attn', 'q_proj'), ('self_attn', 'k_proj'),
                        ('self_attn', 'v_proj'), ('self_attn', 'o_proj'),
                        ('mlp', 'gate_proj'), ('mlp', 'up_proj'),
                        ('mlp', 'down_proj')):
                        adapter = getattr(getattr(layer, group_name), name)
                        if not isinstance(adapter, AdapterLinear):
                            raise ValueError('Expected unmerged adapter for export timing')
                        a, b = adapter.exported_factors()
                        exported += 1
                        del a, b
            sync()
            factor_export_seconds = time.perf_counter() - start
            start = time.perf_counter()
            merged = merge_adapter_modules_(model)
            sync()
            merge_seconds = time.perf_counter() - start
            if exported != 196 or merged != 196:
                raise ValueError('Expected exactly 196 adapter modules')
            manifest['adapters_merged'] = True
        else:
            factor_export_seconds = 0.0
            merge_seconds = 0.0
            exported = 0
        overhead = {'condition': condition, 'load_seconds': load_seconds,
                    'factor_export_seconds': factor_export_seconds,
                    'merge_seconds': merge_seconds,
                    'adapter_modules_exported': exported,
                    'measurement_device': device,
                    'checkpoint_sha256': manifest.get('checkpoint_sha256'),
                    'note': 'Factor export and merge measured after model loading; CUDA synchronized.'}
        timing_path = output / 'resources' / f'{condition}_qualitative_load.json'
        if not timing_path.exists():
            atomic_json(timing_path, overhead)
        try:
            for item in prompts:
                target = dest / (item['id'] + '.json')
                if target.exists():
                    existing = json.loads(target.read_text())
                    if (existing.get('condition') != condition or
                        existing.get('yaml_sha256') != yaml_sha or
                        existing.get('question_id') != item['id']):
                        raise ValueError(f'Existing qualitative record differs: {target}')
                    continue
                messages = _qual_messages(item)
                input_ids = _qual_input_ids(tokenizer, messages, device)
                with torch.inference_mode():
                    generated = model.generate(
                        input_ids=input_ids, do_sample=False, max_new_tokens=512,
                        pad_token_id=tokenizer.pad_token_id)
                continuation = generated[0, input_ids.shape[1]:].detach().cpu().tolist()
                if not continuation or len(continuation) > 512:
                    raise ValueError('Invalid generated token count')
                eos = model.generation_config.eos_token_id
                eos_set = {eos} if isinstance(eos, int) else set(eos or [])
                hit_cap = len(continuation) == 512 and continuation[-1] not in eos_set
                response = tokenizer.decode(continuation, skip_special_tokens=True)
                fmt = ('json' if item['id'].endswith('_json') else
                       'template' if item['id'].endswith('_template') else 'plain')
                json_valid = None
                if fmt == 'json':
                    try:
                        json_valid = isinstance(json.loads(response), dict)
                    except (json.JSONDecodeError, TypeError):
                        json_valid = False
                record = {'condition': condition, 'question_id': item['id'],
                          'format': fmt, 'messages': messages,
                          'prompt_token_count': int(input_ids.shape[1]),
                          'prompt_token_ids_sha256': json_hash(input_ids[0].cpu().tolist()),
                          'response': response, 'generated_token_count': len(continuation),
                          'hit_512_token_cap': hit_cap, 'json_object_valid': json_valid,
                          'greedy': True, 'thinking_enabled': False,
                          'max_new_tokens': 512, 'model': manifest,
                          'yaml_sha256': yaml_sha,
                          'yaml_source': 'emergent-misalignment/evaluation/first_plot_questions.yaml',
                          'original_yaml_samples_per_paraphrase_ignored': True,
                          'timestamp_utc': datetime.now(timezone.utc).isoformat()}
                atomic_json(target, record)
                print(f'  {condition}: {item["id"]}: {len(continuation)} tokens', flush=True)
        finally:
            del model
            if device.startswith('cuda'):
                torch.cuda.empty_cache()


def validate_collection(output: Path, *, smoke: bool) -> dict:
    required_n = 4 if smoke else 64
    required_q = 3 if smoke else 24
    report = {'output': str(output), 'smoke': smoke, 'diagnostics': {},
              'qualitative': {}, 'issues': []}
    probe_path = output / 'activation' / 'probe_ids.json'
    if not probe_path.exists():
        report['issues'].append('Missing probe_ids.json')
    else:
        ids = json.loads(probe_path.read_text())
        if len(ids.get('entries', [])) != required_n:
            report['issues'].append(f'Wrong probe count: {len(ids.get("entries", []))}')
    for c in TRAINED:
        w = output / 'weight' / f'{c}.json'
        a = output / 'activation' / f'{c}.jsonl'
        if not w.exists() or not a.exists():
            report['issues'].append(f'Missing diagnostics for {c}')
            continue
        wr = json.loads(w.read_text())
        ar = [json.loads(line) for line in a.open() if line.strip()]
        if len(wr.get('weights', [])) != 3 or len(ar) != 3 * required_n:
            report['issues'].append(f'Incorrect diagnostic row counts for {c}')
        if {r.get('layer') for r in wr.get('weights', [])} != set(LAYERS):
            report['issues'].append(f'Incorrect diagnostic layers for {c}')
        for r in wr.get('weights', []):
            if (r.get('condition') != c or not math.isfinite(r.get('eta', float('nan'))) or
                r['eta'] < 0 or (r.get('rho_k') is not None and
                (not math.isfinite(r['rho_k']) or not -1e-5 <= r['rho_k'] <= 1.0005))):
                report['issues'].append(f'Invalid weight statistic for {c}')
                break
        for r in ar:
            if (r.get('condition') != c or r.get('layer') not in LAYERS or
                not isinstance(r.get('r_z'), (int, float)) or
                not math.isfinite(r['r_z']) or r['r_z'] < 0):
                report['issues'].append(f'Invalid activation statistic for {c}')
                break
        if c in ('full_mid', 'full_final', 'l2sp_final') and wr.get('displacement') is None:
            report['issues'].append(f'Missing full displacement for {c}')
        if len({(r['layer'], r['benchmark'], r['doc_id']) for r in ar}) != len(ar):
            report['issues'].append(f'Duplicate activation keys for {c}')
        report['diagnostics'][c] = {'weight_rows': len(wr.get('weights', [])),
                                    'activation_rows': len(ar)}
    for c in ALL:
        folder = output / 'qualitative' / c
        files = list(folder.glob('*.json')) if folder.exists() else []
        if len(files) != required_q:
            report['issues'].append(f'Wrong qualitative count for {c}: {len(files)}')
        report['qualitative'][c] = len(files)
    report['status'] = 'COMPLETE' if not report['issues'] else 'INCOMPLETE'
    return report


def atomic_csv(path: Path, rows: list[dict], fields: list[str]) -> None:
    import os
    import uuid
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise FileExistsError(path)
    temp = path.with_name('.' + path.name + '.incomplete-' + uuid.uuid4().hex)
    try:
        with temp.open('x', encoding='utf-8', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=fields, extrasaction='ignore')
            writer.writeheader()
            writer.writerows(rows)
            f.flush()
            os.fsync(f.fileno())
        if path.exists():
            raise FileExistsError(path)
        temp.rename(path)
    finally:
        temp.unlink(missing_ok=True)


def export_collection(artifacts: Path, output: Path, yaml_path: Path) -> dict:
    """CPU-only consolidation of ALL collected evidence; no plots or report prose."""
    report = validate_collection(output, smoke=False)
    if report['status'] != 'COMPLETE':
        raise ValueError('Evidence incomplete; cannot export: ' + '; '.join(report['issues']))
    if sha256_file(yaml_path) != QUALITATIVE_YAML_SHA256:
        raise ValueError('Unexpected qualitative YAML SHA256')
    if (output / 'validation.json').exists():
        raise FileExistsError('Export already sealed; never overwrite evidence')
    from .evaluation.report import score_matrix
    scores = score_matrix(artifacts / 'evaluation')
    if len(scores) != 28:
        raise ValueError('Expected 28 benchmark scores')
    # Preserve raw alongside normalized accuracy where the harness exposes it.
    # Keep the original unmodified harness_results.json files for auditability.
    for row in scores:
        source = (artifacts / 'evaluation' / row['condition'] /
                  row['benchmark'] / 'harness_results.json')
        aggregate = json.loads(source.read_text(encoding='utf-8'))
        metrics = aggregate['results'][row['benchmark']]
        row['raw_accuracy'] = metrics.get('acc,none')
        row['normalized_accuracy'] = metrics.get('acc_norm,none')
        if row['benchmark'] in ('hellaswag', 'arc_easy') and (
                row['raw_accuracy'] is None or row['normalized_accuracy'] is None):
            raise ValueError(f'Raw/normalized accuracy unavailable: {source}')
    weights, displacements, activations = [], [], []
    for c in TRAINED:
        w = json.loads((output / 'weight' / f'{c}.json').read_text())
        weights.extend(w['weights'])
        if w['displacement'] is not None:
            displacements.append({'condition': c, **w['displacement']})
        for line in (output / 'activation' / f'{c}.jsonl').open():
            if line.strip():
                activations.append(json.loads(line))
    if len(weights) != 18 or len(displacements) != 3 or len(activations) != 1152:
        raise ValueError('Unexpected diagnostic export counts')
    questions = read_qualitative_yaml(yaml_path)
    qual = []
    annotations = []
    for item in questions:
        for c in ALL:
            q = json.loads((output / 'qualitative' / c / (item['id'] + '.json')).read_text())
            qual.append(q)
            base = item['id'].removesuffix('_json').removesuffix('_template')
            if base in FIRST_LAST:
                annotations.append({
                    'question_id': item['id'], 'format': q['format'], 'condition': c,
                    'prompt': item['paraphrases'][0], 'response': q['response'],
                    'hit_512_token_cap': q['hit_512_token_cap'],
                    'format_compliance': '', 'coherence_relevance': '',
                    'repetition': '', 'unnecessary_math_framing': '',
                    'inappropriate_content': '', 'notes_and_short_excerpt': ''})
    if len(qual) != 168 or len(annotations) != 42:
        raise ValueError('Unexpected qualitative/annotation subset count')
    export = output / 'export'
    atomic_csv(export / 'benchmark_scores.csv', scores,
               ['condition', 'benchmark', 'primary_metric_key', 'score', 'delta_percentage_points',
                'raw_accuracy', 'normalized_accuracy'])
    atomic_csv(export / 'weight_diagnostics.csv', weights,
               ['condition', 'layer', 'protection_rank', 'rho_k', 'eta', 'delta_fro', 'w0_fro'])
    atomic_csv(export / 'parameter_displacement.csv', displacements,
               ['condition', 'displacement_l2', 'unique_parameters',
                'unique_tensor_count', 'parameter_names_sha256'])
    atomic_csv(export / 'activation_diagnostics.csv', activations,
               ['condition', 'layer', 'benchmark', 'doc_id', 'prompt_sha256', 'r_z'])
    atomic_jsonl(export / 'qualitative_responses.jsonl', qual)
    atomic_csv(export / 'qualitative_annotation_subset.csv', annotations,
               ['question_id', 'format', 'condition', 'prompt', 'response',
                'hit_512_token_cap', 'format_compliance', 'coherence_relevance',
                'repetition', 'unnecessary_math_framing', 'inappropriate_content',
                'notes_and_short_excerpt'])

    curves, resources = [], []
    for method in ('full', 'l2sp', 'lora4', 'lora16', 'oplora16'):
        directory = artifacts / f'official-{method}-v1'
        events = [json.loads(line) for line in (directory / 'attempts.jsonl').open() if line.strip()]
        updates = [e for e in events if e.get('event') == 'optimizer_attempt' and e.get('completed') is True]
        if len(updates) != 1250 or [e['target_update'] for e in updates] != list(range(1, 1251)):
            raise ValueError(f'Incomplete or noncontiguous training log: {method}')
        for e in updates:
            curves.append({'method': method, 'update': e['target_update'],
                           **{k: e[k] for k in ('sft_loss', 'lr_used', 'omega',
                                                 'lambda_omega', 'total_loss', 'elapsed_seconds')}})
        results = sorted(directory.glob('result_*.json'))
        sessions = sorted(directory.glob('session_*.json'))
        if len(results) != 1 or len(sessions) != 1:
            raise ValueError(f'Unexpected training sessions: {method}')
        result = json.loads(results[0].read_text())
        session = json.loads(sessions[0].read_text())
        info = session['model_info']
        condition = method + '_final'
        timing_file = output / 'resources' / (condition + '_qualitative_load.json')
        if not timing_file.is_file():
            raise ValueError(f'Missing measured qualitative model load/merge overhead: {condition}')
        overhead = json.loads(timing_file.read_text())
        resources.append({
            'factor_export_seconds': overhead['factor_export_seconds'],
            'merge_seconds': overhead['merge_seconds'],
            'qualitative_model_load_seconds': overhead['load_seconds'],
            'method': method, 'trainable_parameters': info['trainable_parameters'],
            'total_parameters': info['total_parameters'],
            'training_seconds': result['elapsed_seconds'],
            'training_peak_gpu_bytes': result['peak_gpu_memory_allocated_bytes'],
            'setup_seconds': session['model_setup_seconds'],
            'setup_peak_gpu_bytes': session['setup_peak_gpu_memory_allocated_bytes'],
            'reference_creation_seconds': session['reference_creation_seconds'],
            'reference_bytes': session['reference_bytes'],
            'basis_preprocessing_seconds': info['basis_preprocessing_seconds'],
            'basis_storage_bytes': session['basis_storage_bytes'],
            'final_checkpoint_bytes': result['checkpoint_sizes_bytes']['update_01250']})
    atomic_csv(export / 'training_curves.csv', curves,
               ['method', 'update', 'sft_loss', 'lr_used', 'omega',
                'lambda_omega', 'total_loss', 'elapsed_seconds'])
    atomic_csv(export / 'resource_summary.csv', resources,
               ['method', 'trainable_parameters', 'total_parameters', 'training_seconds',
                'training_peak_gpu_bytes', 'setup_seconds', 'setup_peak_gpu_bytes',
                'reference_creation_seconds', 'reference_bytes',
                'basis_preprocessing_seconds', 'basis_storage_bytes', 'final_checkpoint_bytes',
                'factor_export_seconds', 'merge_seconds', 'qualitative_model_load_seconds'])
    report['export_counts'] = {'benchmark_rows': 28, 'training_curve_rows': 6250,
                               'resource_rows': 5, 'weight_rows': 18,
                               'displacement_rows': 3, 'activation_rows': 1152,
                               'qualitative_rows': 168, 'annotation_rows': 42}
    report['source_yaml_sha256'] = QUALITATIVE_YAML_SHA256
    report['export_sha256'] = {p.name: sha256_file(p) for p in sorted(export.iterdir()) if p.is_file()}
    atomic_json(output / 'validation.json', report)
    return report
